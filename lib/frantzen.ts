type CapturedRecipe = Omit<FrantzenRecipe, "image" | "sourceLabel" | "sourceImage" | "sourceImages">;

const capturedRecipe = (captures: number | number[], recipe: CapturedRecipe): FrantzenRecipe => {
  const captureList = Array.isArray(captures) ? captures : [captures];
  return {
    ...recipe,
    image: null,
    sourceLabel: captureList.length === 1 ? `Supplied capture IMG_${captureList[0]}` : `Supplied captures ${captureList.map((capture) => `IMG_${capture}`).join(" and ")}`,
    sourceImage: `/frantzen/sources/img-${captureList[0]}.jpg`,
    sourceImages: captureList.map((capture) => ({ label: `IMG_${capture}`, href: `/frantzen/sources/img-${capture}.jpg` })),
  };
};

