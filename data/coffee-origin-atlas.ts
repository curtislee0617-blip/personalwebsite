function inferRegionSpecies(varieties: string, fallback: string) {
  const hasArabica =
    /Arabica|Bourbon|Typica|Caturra|Catuaí|Catuai|Catimor|Pacas|Pacamara|Gesha|Geisha|SL\d|Ruiru|Batian|K7|N39|KP423|Java|Kent|Mibirizi|Jackson|Marsellesa|Starmaya|Villa Sarchi|Centroamericano|S795|Selection 9|Cauvery|Híbrido de Timor|Ateng|Sigarar|Andungsari|Kartika|Arusha|Dawairi|Udaini|Tufahi|Jaadi|Khawlani|Kurume|Wolisho|JARC|Mundo Novo|Arara|Icatu|Catucaí|Castillo|Colombia|Tabi|Sidra|Typica Mejorado|IHCAFE|Lempira|Parainema|Catisic|Cuscatleco|Pluma/i.test(
      varieties,
    );
  const hasCanephora = /Canephora|Robusta|Conilon|Nganda|Erecta|TR\d|KR wilt/i.test(varieties);
  const hasLiberica = /Liberica/i.test(varieties);

  if (hasArabica && hasCanephora && hasLiberica) return "Arabica, Canephora & Liberica";
  if (hasArabica && hasCanephora) return "Arabica & Canephora";
  if (hasCanephora && hasLiberica) return "Canephora & Liberica";
  if (hasArabica && hasLiberica) return "Arabica & Liberica";
  if (hasCanephora) return "Canephora";
  if (hasLiberica) return "Liberica";
  if (hasArabica) return "Arabica";
  return fallback;
}

function buildOrigin(origin: CoffeeOriginSeed): CoffeeAtlasOrigin {
  const details = originDetails[origin.iso];
  if (!details) {
    throw new Error(`Missing regional coffee detail for ${origin.iso}`);
  }

  const growingRegions = details.growingRegions.map((region) => {
    const coordinates = growingRegionCoordinates[origin.iso]?.[region.id];
    if (!coordinates) {
      throw new Error(`Missing map coordinates for ${origin.iso}/${region.id}`);
    }

    return {
      ...region,
      coordinates,
      species: region.species ?? inferRegionSpecies(region.varieties, origin.species),
    };
  });

  return { ...origin, ...details, growingRegions };
}

export const coffeeOrigins: CoffeeAtlasOrigin[] = [
  ...(coreCoffeeOrigins as CoffeeOriginSeed[]),
  ...additionalCoffeeOrigins,
].map(buildOrigin);

export const coffeeOriginCount = coffeeOrigins.length;
export const coffeeGrowingRegionCount = coffeeOrigins.reduce(
  (total, origin) => total + origin.growingRegions.length,
  0,
);
